DROP VIEW IF EXISTS `VUE_VOYAGES_DISPONIBLES`;
CREATE OR REPLACE VIEW `VUE_VOYAGES_DISPONIBLES` AS
SELECT 
    v.ID_VOYAGE,
    v.CODE_VOYAGE,
    v.DATE_HEURE_DEPART_PREVUE,
    v.DATE_HEURE_ARRIVEE_PREVUE,
    v.STATUT_VOYAGE,
    l.CODE_LIGNE,
    v_dep.NOM_VILLE AS VILLE_DEPART,
    v_arr.NOM_VILLE AS VILLE_ARRIVEE,
    b.IMMATRICULATION AS BUS_IMMATRICULATION,
    b.NB_PLACES AS CAPACITE_TOTALE,
    cb.LIBELLE_CLASSE AS CLASSE_BUS,
    ag.NOM_AGENCE AS AGENCE_DEPART,
    COUNT(blt.ID_BILLET) AS PLACES_OCCUPEES,
    (b.NB_PLACES - COUNT(blt.ID_BILLET)) AS PLACES_RESTANTES,
    COALESCE(MIN(t.PRIX_XAF), 0.00) AS TARIF_BASE_XAF
FROM VOYAGE v
INNER JOIN LIGNE l ON v.ID_LIGNE = l.ID_LIGNE
INNER JOIN VILLE v_dep ON l.ID_VILLE_DEPART = v_dep.ID_VILLE
INNER JOIN VILLE v_arr ON l.ID_VILLE_ARRIVEE = v_arr.ID_VILLE
INNER JOIN BUS b ON v.ID_BUS = b.ID_BUS
INNER JOIN CLASSE_BUS cb ON b.ID_CLASSE = cb.ID_CLASSE
INNER JOIN AGENCE ag ON v.ID_AGENCE = ag.ID_AGENCE
LEFT JOIN TARIF t ON t.ID_LIGNE = l.ID_LIGNE AND t.ID_CLASSE = b.ID_CLASSE
LEFT JOIN BILLET blt ON blt.ID_VOYAGE = v.ID_VOYAGE AND blt.STATUT_BILLET IN ('VALIDE', 'EMBARQUE')
WHERE v.STATUT_VOYAGE IN ('PROGRAMME', 'OUVERT', 'CONFIRME')
GROUP BY 
    v.ID_VOYAGE, v.CODE_VOYAGE, v.DATE_HEURE_DEPART_PREVUE, v.DATE_HEURE_ARRIVEE_PREVUE,
    v.STATUT_VOYAGE, l.CODE_LIGNE, v_dep.NOM_VILLE, v_arr.NOM_VILLE,
    b.IMMATRICULATION, b.NB_PLACES, cb.LIBELLE_CLASSE, ag.NOM_AGENCE;

