-- PROCÉDURE 1 : Transaction complète de vente et émission de billet
DROP PROCEDURE IF EXISTS `SP_RESERVER_BILLET`//
CREATE PROCEDURE `SP_RESERVER_BILLET` (
    IN  p_id_voyage        VARCHAR(20),
    IN  p_id_client        VARCHAR(20),
    IN  p_id_employe       VARCHAR(20),
    IN  p_id_mode_paiement VARCHAR(20),
    IN  p_id_cloture       VARCHAR(20),
    IN  p_id_categorie     VARCHAR(20),
    IN  p_num_siege        INT,
    IN  p_prix_xaf         DECIMAL(12,2),
    OUT p_id_billet_genere VARCHAR(20),
    OUT p_code_retour      INT,
    OUT p_message_retour   VARCHAR(255)
)
proc_label: BEGIN
    DECLARE v_siege_pris INT DEFAULT 0;
    DECLARE v_code_billet VARCHAR(30);
    DECLARE v_code_res VARCHAR(20);
    DECLARE v_cle_hmac VARCHAR(128);

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        ROLLBACK;
        SET p_code_retour = -1;
        SET p_message_retour = 'Erreur SQL lors de l''exécution de SP_RESERVER_BILLET.';
    END;

    -- 1. Vérification disponibilité
    SELECT COUNT(*) INTO v_siege_pris
    FROM BILLET
    WHERE ID_VOYAGE = p_id_voyage
      AND NUM_SIEGE = p_num_siege
      AND STATUT_BILLET IN ('VALIDE', 'EMBARQUE');

    IF v_siege_pris > 0 THEN
        SET p_code_retour = 1;
        SET p_message_retour = 'Ce siège est déjà réservé ou vendu.';
        LEAVE proc_label;
    END IF;

    -- 2. Transaction ACID
    START TRANSACTION;

    SET p_id_billet_genere = CONCAT('BLT-', DATE_FORMAT(NOW(), '%y%m%d%H%i%s'), '-', SUBSTRING(MD5(RAND()), 1, 4));
    SET v_code_billet = CONCAT('GT-', DATE_FORMAT(NOW(), '%d%m%y'), '-', p_num_siege, '-', SUBSTRING(MD5(RAND()), 1, 5));
    SET v_code_res = CONCAT('RES-', SUBSTRING(MD5(CONCAT(NOW(), RAND())), 1, 8));
    SET v_cle_hmac = SHA2(CONCAT(v_code_billet, p_id_client, p_num_siege, NOW()), 256);

    INSERT INTO BILLET (
        ID_BILLET, ID_CLIENT, ID_VOYAGE, ID_CATEGORIE, ID_EMPLOYE,
        CODE_BILLET, CODE_RESERVATION, NUM_SIEGE, TYPE_BILLET, CANAL_VENTE,
        DATE_EMISSION, DATE_VALIDITE, PRIX_APPLIQUE_XAF, EST_GRATUIT,
        VOYAGE_PAR_TIERS, COPIE_PIECE_VERIFIEE, SIGNATURE_HMAC, STATUT_BILLET
    ) VALUES (
        p_id_billet_genere, p_id_client, p_id_voyage, p_id_categorie, p_id_employe,
        v_code_billet, v_code_res, p_num_siege, 'ALLER_SIMPLE', 'GUICHET',
        NOW(), CURDATE(), p_prix_xaf, 0,
        0, 1, v_cle_hmac, 'VALIDE'
    );

    INSERT INTO PAIEMENT (
        ID_PAIEMENT, ID_MODE, ID_CLOTURE, ID_BILLET,
        REFERENCE_TRANSACTION, MONTANT_PAYE_XAF, DATE_PAIEMENT, STATUT_PAIEMENT
    ) VALUES (
        CONCAT('PAI-', DATE_FORMAT(NOW(), '%y%m%d%H%i%s'), '-', SUBSTRING(MD5(RAND()), 1, 4)),
        p_id_mode_paiement,
        p_id_cloture,
        p_id_billet_genere,
        CONCAT('TXN-', DATE_FORMAT(NOW(), '%y%m%d%H%i%s')),
        p_prix_xaf,
        NOW(),
        'VALIDE'
    );

    COMMIT;

    SET p_code_retour = 0;
    SET p_message_retour = 'Billet émis et paiement validé avec succès.';
END//

-- PROCÉDURE 2 : Clôture de session de caisse avec calcul automatique d'écart
DROP PROCEDURE IF EXISTS `SP_CLOTURER_SESSION_CAISSE`//
CREATE PROCEDURE `SP_CLOTURER_SESSION_CAISSE` (
    IN  p_id_cloture          VARCHAR(20),
    IN  p_id_employe_chef     VARCHAR(20),
    IN  p_montant_physique    DECIMAL(12,2),
    OUT p_montant_theorique   DECIMAL(12,2),
    OUT p_ecart_constate      DECIMAL(12,2),
    OUT p_message_cloture     VARCHAR(255)
)
BEGIN
    SELECT COALESCE(SUM(MONTANT_PAYE_XAF), 0.00) INTO p_montant_theorique
    FROM PAIEMENT
    WHERE ID_CLOTURE = p_id_cloture AND STATUT_PAIEMENT = 'VALIDE';

    SET p_ecart_constate = p_montant_physique - p_montant_theorique;

    UPDATE CLOTURE_CAISSE
    SET ID_EMPLOYE_CHEF = p_id_employe_chef,
        HEURE_FERMETURE = CURTIME(),
        MONTANT_THEORIQUE_XAF = p_montant_theorique,
        MONTANT_COMPTE_XAF = p_montant_physique,
        ECART_CONSTATE_XAF = p_ecart_constate,
        OBSERVATION_CLOTURE = CONCAT('Clôturé le ', NOW(), ' par ', p_id_employe_chef)
    WHERE ID_CLOTURE = p_id_cloture;

    SET p_message_cloture = CONCAT('Clôture enregistrée : Théorique = ', p_montant_theorique, ' XAF | Physique = ', p_montant_physique, ' XAF | Écart = ', p_ecart_constate, ' XAF');
END//

-- PROCÉDURE 3 : Calcul des indicateurs d'activité quotidienne d'une agence
DROP PROCEDURE IF EXISTS `SP_STATS_ACTIVITE_AGENCE`//
CREATE PROCEDURE `SP_STATS_ACTIVITE_AGENCE` (
    IN  p_id_agence       VARCHAR(20),
    IN  p_date_jour       DATE,
    OUT p_nb_billets      INT,
    OUT p_recette_billets DECIMAL(14,2),
    OUT p_recette_colis   DECIMAL(14,2)
)
BEGIN
    SELECT 
        COUNT(blt.ID_BILLET),
        COALESCE(SUM(blt.PRIX_APPLIQUE_XAF), 0.00)
    INTO p_nb_billets, p_recette_billets
    FROM BILLET blt
    INNER JOIN VOYAGE v ON blt.ID_VOYAGE = v.ID_VOYAGE
    WHERE v.ID_AGENCE = p_id_agence
      AND DATE(blt.DATE_EMISSION) = p_date_jour
      AND blt.STATUT_BILLET IN ('VALIDE', 'EMBARQUE');

    SELECT 
        COALESCE(SUM(cls.FRAIS_EXPEDITION_XAF), 0.00)
    INTO p_recette_colis
    FROM COLIS cls
    WHERE cls.ID_AGENCE_DEPOT = p_id_agence
      AND DATE(cls.DATE_ENREGISTREMENT) = p_date_jour;
END//

