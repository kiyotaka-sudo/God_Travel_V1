CREATE TABLE IF NOT EXISTS `COMPAGNIE` (
    `ID_COMPAGNIE` VARCHAR(20) NOT NULL COMMENT 'Identifiant unique de la compagnie',
    `RAISON_SOCIALE` VARCHAR(100) NOT NULL COMMENT 'Raison sociale officielle',
    `SIGLE` VARCHAR(20) NOT NULL COMMENT 'Sigle commercial (ex: UNITED)',
    `NUM_CONTRIBUABLE` VARCHAR(30) NOT NULL COMMENT 'Numéro fiscal contribuable',
